// Check if an emoji supports skin tone modifiers
export const supportsSkinTone = (emoji) => {
  return SKIN_TONE_SUPPORTED.includes(emoji);
};

// Apply skin tone to an emoji if supported
export const applySkinTone = (emoji, skinTone) => {
  if (!skinTone || skinTone === 'default' || !supportsSkinTone(emoji)) {
    return emoji;
  }
  const modifier = SKIN_TONE_MODIFIERS[skinTone];
  return modifier ? emoji + modifier : emoji;
};